#!/usr/bin/env python3
"""Make Assets.xcassets/RagnarokMark.symbolset/ragnarok.svg: the Ragnarok mark (Resources/AppIcon.svg's two lemniscates,
the horizon line and the centre dot) as a custom SF Symbol. Needs shapely (pieces are merged into one outline per
weight; the symbol compiler cuts overlaps out instead of joining them). Run: python make-symbol.py"""
import math, os
from shapely.geometry import LineString, Point, box
from shapely.ops import unary_union
from shapely.affinity import rotate

def cubic(p0, p1, p2, p3, n=80):
    return [tuple((1-t)**3*a + 3*(1-t)**2*t*b + 3*(1-t)*t*t*c + t**3*d for a, b, c, d in zip(p0, p1, p2, p3))
            for t in [i / n for i in range(n + 1)]]

petal = cubic((0, 0), (59, -88), (45, -186), (0, -186)) + cubic((0, -186), (-45, -186), (-59, -88), (0, 0))[1:]

def mark(w):  # w = half stroke, icon units
    parts = [rotate(LineString(petal), a, origin=(0, 0)).buffer(w, join_style=1, cap_style=1) for a in (0, 90, 180, 270)]
    parts.append(box(-240, -w * 0.8, 240, w * 0.8))
    parts.append(Point(0, 0).buffer(max(24, w * 2.2), quad_segs=16))
    return unary_union(parts)

S = 0.25  # icon units -> template units

def path(geom, cx, cy):
    polys = [geom] if geom.geom_type == "Polygon" else list(geom.geoms)
    out = []
    for p in polys:
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)
            out.append("M" + " L".join(f"{cx + x * S:.2f},{cy + y * S:.2f}" for x, y in pts) + " Z")
    return " ".join(out)

rows = {"S": (696, 625.541), "M": (1126, 1055.54), "L": (1556, 1485.54)}
glyphs = [("Ultralight-S", 600, "S", 1.0), ("Regular-S", 1490, "S", 2.1), ("Black-S", 2380, "S", 4.2), ("Regular-M", 1490, "M", 2.1)]
guides, syms = [], []
for row, (base, cap) in rows.items():
    guides.append(f'<line id="Baseline-{row}" x1="263" x2="3036" y1="{base}" y2="{base}" stroke="black" stroke-width="0.5"/>')
    guides.append(f'<line id="Capline-{row}" x1="263" x2="3036" y1="{cap}" y2="{cap}" stroke="black" stroke-width="0.5"/>')
for name, cx, row, w in glyphs:
    base, cap = rows[row]; cy = (base + cap) / 2
    g = mark(w / S)
    minx, _, maxx, _ = g.bounds
    l, r = cx + minx * S, cx + maxx * S
    guides.append(f'<line id="left-margin-{name}" x1="{l:.2f}" x2="{l:.2f}" y1="{cy-60:.0f}" y2="{cy+60:.0f}" stroke="#00AEEF" stroke-width="0.5"/>')
    guides.append(f'<line id="right-margin-{name}" x1="{r:.2f}" x2="{r:.2f}" y1="{cy-60:.0f}" y2="{cy+60:.0f}" stroke="#00AEEF" stroke-width="0.5"/>')
    syms.append(f'  <g id="{name}"><path d="{path(g, cx, cy)}"/></g>')
svg = ('<?xml version="1.0" encoding="UTF-8"?>\n<!-- Ragnarok mark as a custom SF Symbol; generated by make-symbol.py -->\n'
       '<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="3300" height="2200">\n'
       ' <g id="Notes"><text x="18" y="40" font-size="13">Ragnarok mark</text></g>\n <g id="Guides">\n  '
       + "\n  ".join(guides) + '\n </g>\n <g id="Symbols">\n' + "\n".join(syms) + '\n </g>\n</svg>\n')
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "Assets.xcassets/RagnarokMark.symbolset/ragnarok.svg"), "w").write(svg)
print("wrote ragnarok.svg")
